import { useMemo, useState } from "react";
import {
  CheckCircle2,
  ChevronLeft,
  Clock,
  Copy,
  Lock,
  ShieldBan,
  Unlock,
} from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { DEVICE } from "@/lib/diagnostic/knowledge";
import { useDiagnosticStore } from "@/lib/diagnostic/store";
import { cn } from "@/lib/utils";

const RISK_LABEL = {
  none: "No risk",
  low: "Low risk",
  medium: "Medium risk",
  high: "High risk",
};

export function ProtocolStep() {
  const setStep = useDiagnosticStore((s) => s.setStep);
  const getPrimary = useDiagnosticStore((s) => s.getPrimary);
  const getDiagnoses = useDiagnosticStore((s) => s.getDiagnoses);
  const answers = useDiagnosticStore((s) => s.answers);
  const startedAt = useDiagnosticStore((s) => s.startedAt);
  const chiefComplaint = useDiagnosticStore((s) => s.chiefComplaint);
  const primary = getPrimary();
  const diagnoses = getDiagnoses();

  const [done, setDone] = useState<Record<string, boolean>>({});
  const [factoryUnlocked, setFactoryUnlocked] = useState(false);
  const [copied, setCopied] = useState(false);

  const steps = primary?.treatmentOrder ?? [];
  const nonDestructiveDone = steps
    .filter((s) => !s.destructive)
    .every((s) => done[s.id]);

  const report = useMemo(() => {
    const lines = [
      "PodScope Case Report — HomePod (2nd generation)",
      `Device: ${DEVICE.name} (${DEVICE.codename})`,
      `Chief complaint: ${chiefComplaint ?? "—"}`,
      `Case opened: ${startedAt ?? "—"}`,
      "",
      "Vitals:",
      ...Object.entries(answers).map(([k, v]) => `  - ${k}: ${Array.isArray(v) ? v.join(", ") : String(v)}`),
      "",
      `Primary diagnosis: ${primary?.title ?? "—"} (score ${primary?.score ?? 0}, ${primary?.confidence ?? "—"})`,
      `Mechanism: ${primary?.mechanism ?? "—"}`,
      "",
      "Differential ranking:",
      ...diagnoses.slice(0, 5).map((d, i) => `  ${i + 1}. ${d.title} [${d.score}] ${d.severity}`),
      "",
      "Protocol:",
      ...steps.map(
        (s) =>
          `  - [${done[s.id] ? "x" : " "}] ${s.title}${s.destructive ? " (DESTRUCTIVE)" : ""}`,
      ),
      "",
      "Contraindications observed:",
      ...(primary?.contraindications.map((c) => `  - ${c}`) ?? ["  —"]),
      "",
      "Generated by PodScope — independent diagnostic guide, not Apple support.",
    ];
    return lines.join("\n");
  }, [answers, chiefComplaint, diagnoses, done, primary, startedAt, steps]);

  async function copyReport() {
    try {
      await navigator.clipboard.writeText(report);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      /* ignore */
    }
  }

  if (!primary) {
    return (
      <div className="space-y-4">
        <p className="text-sm text-[var(--color-fg-muted)]">Complete vitals first.</p>
        <Button onClick={() => setStep("vitals")}>Back to vitals</Button>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <section className="space-y-2">
        <Badge variant="outline">Treatment protocol</Badge>
        <h1 className="font-display text-2xl font-semibold tracking-tight sm:text-3xl">
          Ordered care for: {primary.title}
        </h1>
        <p className="max-w-2xl text-sm text-[var(--color-fg-muted)] leading-relaxed">
          Follow steps in order. Destructive actions stay locked until non-destructive care is marked
          complete — stopping the “10-second handoff” reflex and the rest-and-hope spiral.
        </p>
      </section>

      <div className="grid gap-4 lg:grid-cols-[1.5fr_1fr]">
        <div className="space-y-3">
          {steps.map((step, i) => {
            const isFactory = Boolean(step.destructive || step.gated);
            const locked = isFactory && !factoryUnlocked && !nonDestructiveDone;
            const isDone = Boolean(done[step.id]);

            return (
              <Card
                key={step.id}
                className={cn(
                  locked && "opacity-60",
                  isDone && "border-[var(--color-ok)]/25",
                  isFactory && factoryUnlocked && "border-[var(--color-critical)]/30",
                )}
              >
                <CardHeader className="pb-2">
                  <div className="flex flex-wrap items-center gap-2">
                    <span className="flex h-7 w-7 items-center justify-center rounded-full border border-[var(--color-border)] font-mono text-xs text-[var(--color-fg-muted)]">
                      {i + 1}
                    </span>
                    <CardTitle className="text-base">{step.title}</CardTitle>
                    <Badge variant={step.risk === "high" ? "critical" : step.risk === "low" ? "ok" : "default"}>
                      {RISK_LABEL[step.risk]}
                    </Badge>
                    {isFactory && (
                      <Badge variant="critical">{locked ? "Gated" : "Unlocked"}</Badge>
                    )}
                  </div>
                  <CardDescription className="flex items-center gap-1.5 pt-1">
                    <Clock className="size-3.5" />
                    {step.duration}
                  </CardDescription>
                </CardHeader>
                <CardContent className="space-y-3">
                  <p className="text-sm text-[var(--color-fg-muted)] leading-relaxed">{step.detail}</p>
                  {step.gateReason && (
                    <p className="rounded-[var(--radius-sm)] border border-[var(--color-critical)]/20 bg-[var(--color-critical-dim)]/40 px-3 py-2 text-xs text-[var(--color-critical)] leading-relaxed">
                      {step.gateReason}
                    </p>
                  )}
                  <div className="flex flex-wrap gap-2">
                    {locked ? (
                      <Button
                        size="sm"
                        variant="secondary"
                        onClick={() => {
                          if (nonDestructiveDone) setFactoryUnlocked(true);
                        }}
                        disabled={!nonDestructiveDone}
                      >
                        <Lock className="size-3.5" />
                        {nonDestructiveDone ? "Unlock destructive step" : "Complete prior steps first"}
                      </Button>
                    ) : (
                      <>
                        {isFactory && !factoryUnlocked && nonDestructiveDone && (
                          <Button size="sm" variant="destructive" onClick={() => setFactoryUnlocked(true)}>
                            <Unlock className="size-3.5" />
                            Unlock factory reset
                          </Button>
                        )}
                        <Button
                          size="sm"
                          variant={isDone ? "secondary" : "default"}
                          disabled={isFactory && !factoryUnlocked}
                          onClick={() => setDone((d) => ({ ...d, [step.id]: !d[step.id] }))}
                        >
                          <CheckCircle2 className="size-3.5" />
                          {isDone ? "Mark incomplete" : "Mark complete"}
                        </Button>
                      </>
                    )}
                  </div>
                </CardContent>
              </Card>
            );
          })}
        </div>

        <div className="space-y-4">
          <Card className="border-[var(--color-warn)]/25">
            <CardHeader>
              <div className="mb-1 flex items-center gap-2 text-[var(--color-warn)]">
                <ShieldBan className="size-4" />
                <span className="text-xs font-medium uppercase tracking-wider">Still forbidden</span>
              </div>
              <CardTitle className="text-base">Do not skip to comfort rituals</CardTitle>
            </CardHeader>
            <CardContent className="space-y-2 text-xs text-[var(--color-fg-muted)] leading-relaxed">
              <p>
                No extra 10-second holds “just in case.” No multi-day unplugged recreation time as a
                substitute for this protocol. No treating a dark box with hope alone — that path ends
                as a depressed, signal-less unit with wiped history.
              </p>
              {primary.contraindications.map((c) => (
                <p key={c} className="rounded-[var(--radius-sm)] bg-[var(--color-bg-elevated)] px-3 py-2">
                  {c}
                </p>
              ))}
            </CardContent>
          </Card>

          <Card>
            <CardHeader>
              <CardTitle className="text-base">Case report</CardTitle>
              <CardDescription>Copy for Apple Support or your own notes.</CardDescription>
            </CardHeader>
            <CardContent className="space-y-3">
              <pre className="max-h-56 overflow-auto rounded-[var(--radius-md)] border border-[var(--color-border)] bg-[var(--color-bg)] p-3 font-mono text-[10px] leading-relaxed text-[var(--color-fg-muted)] whitespace-pre-wrap">
                {report}
              </pre>
              <Button variant="secondary" className="w-full" onClick={copyReport}>
                <Copy className="size-3.5" />
                {copied ? "Copied" : "Copy report"}
              </Button>
            </CardContent>
          </Card>

          <Card>
            <CardHeader>
              <CardTitle className="text-base">Outcome check</CardTitle>
            </CardHeader>
            <CardContent className="space-y-2 text-xs text-[var(--color-fg-muted)] leading-relaxed">
              <p>
                <span className="text-[var(--color-ok)] font-medium">Improved: </span>
                Responsive touch, stable idle, Home app no longer “No Response.”
              </p>
              <p>
                <span className="text-[var(--color-warn)] font-medium">Unchanged: </span>
                Re-run vitals once — do not invent a third reset. Escalate per primary diagnosis.
              </p>
              <p>
                <span className="text-[var(--color-critical)] font-medium">Worse / fully dark: </span>
                Stop DIY. Hardware path via Apple Support.
              </p>
            </CardContent>
          </Card>
        </div>
      </div>

      <div className="flex flex-col-reverse gap-3 sm:flex-row sm:justify-between">
        <Button variant="ghost" onClick={() => setStep("differential")}>
          <ChevronLeft className="size-4" />
          Differential
        </Button>
        <Button variant="outline" onClick={() => setStep("intake")}>
          Return to intake
        </Button>
      </div>
    </div>
  );
}
